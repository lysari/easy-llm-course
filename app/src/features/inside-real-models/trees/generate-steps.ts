import type { InferenceSpec } from "@/features/inside-real-models/interfaces/inference-spec.interface";
import type { ModelPart } from "@/features/inside-real-models/interfaces/model-part.interface";
import { count } from "@/shared/utils/format";

export function generateStep(spec: InferenceSpec): ModelPart {
  const layerCount = spec.layers.children?.[0].copies ?? 1;
  const stopSources = [...new Set([...spec.sources, ...spec.stopWord.notes.map((note) => note.source)])];
  return {
    id: "generate",
    icon: "generate",
    title: "Generate",
    summary: "Picks a word, adds it to the end, and runs again until it stops.",
    copies: 1,
    facts: { shape: `1 word per round, up to ${count(spec.context)} words`, weightCount: 0, headline: { value: spec.context, unit: "words at most" }, input: "chances", output: "new words", outputDetail: "new words, one per round", sources: [...spec.sources, ...spec.textSources], notes: [spec.writingNotes.generate], reasons: spec.reasons.generate },
    explanation: "Pick one word from the chances, add it to the end, and run steps 1 to 4 again. Repeat until the stop word comes up or the text is too long.",
    why: "A whole answer is just this loop. Each word is picked without a plan for the next one.",
    story: {
      problem: "One pass through the model gives chances for only one next word. Without this loop, a model could never write more than a single word.",
      demo: "generate",
      when: "Every time you send a message, until the answer is done. Each word you see appear in a chat app is one round of this loop.",
      feeds: "Each picked word's ID goes back in at Embedding, and the loop runs again until it stops.",
      nextId: "embedding",
    },
    formula: { lines: ["repeat: pick, add, run again", "until stop or full"] },
    children: [
      {
        id: "write-round",
        icon: "write-round",
        title: "One writing round",
        summary: "One pass of the loop: pick a word, add it, then check whether to stop.",
        copies: 1,
        facts: { shape: "pick, add, check", weightCount: 0, headline: { value: 1, unit: "word added" }, input: "all words so far", output: "one more word", sources: spec.textSources, notes: [spec.writingNotes["write-round"]], reasons: spec.reasons["write-round"] },
        explanation: "One pass of the loop: pick a word from the chances, add it to the end, then check whether to stop.",
        why: "The model writes left to right and never goes back to change a word.",
        story: {
          problem: "Writing is not done in one go. Without a round that picks, adds and checks, there would be no way to grow an answer one word at a time.",
          demo: "generate",
          when: "Once for every word of an answer: an answer of 100 words takes 100 rounds.",
          feeds: "The longer text goes back into the model for the next round's chances.",
          nextId: "pick",
        },
        formula: { lines: ["word = pick(chances)", "words = [...words, word]"] },
        children: [
          {
            id: "pick",
            icon: "dice",
            title: "Pick one word",
            summary: "Rolls a random number and walks down the chances to choose one word.",
            copies: 1,
            facts: { shape: "1 random roll", weightCount: 0, headline: { value: spec.wordCount, unit: "words to pick from" }, input: "chances", output: "one word", sources: spec.sources, notes: [spec.writingNotes.pick], reasons: spec.reasons.pick },
            explanation: "Roll a random number from 0 to 1, then walk down the chances, taking each away, until the roll runs out. That word is picked.",
            why: "Likely words are picked more often, but not always. That is why the same start can give different endings.",
            story: {
              problem: "The chances say which words are likely, not which one to write. Something has to choose, and always taking the top word gives dull, repeating text, so most apps roll a weighted dice.",
              demo: "generate",
              when: "Once per round. App settings such as temperature, top-k and top-p change the chances just before this roll.",
              feeds: "The picked word is added to the end of the text.",
              nextId: "append",
            },
            formula: { lines: ["roll = roll − chance(word)", "stop at the first roll ≤ 0"] },
            code: "roll = roll - option.chance;",
            groundZero: "action",
          },
          {
            id: "append",
            icon: "append",
            title: "Add it to the end",
            summary: "Adds the picked word's ID to the end of the text, ready for the next round.",
            copies: 1,
            facts: { shape: "1 more ID", weightCount: 0, headline: { value: spec.context, unit: "words at most" }, input: "words and the pick", output: "one word longer", inputDetail: "words so far and the picked word", sources: spec.sources, notes: [spec.writingNotes.append], reasons: spec.reasons.append },
            explanation: "Append the picked word's ID to the input, ready for the next round.",
            why: "The model's own guess becomes part of what it reads next.",
            story: {
              problem: "The model reads only what is in its text. Without adding the picked word, the next round would see the same words and guess the same way again.",
              demo: "generate",
              when: "Once per round, right after the pick, for every word of the answer.",
              feeds: "The text, now one word longer, goes to the stop check.",
              nextId: "stop-check",
            },
            formula: { lines: ["ids = [...ids, picked]"] },
            code: "ids.push(picked);",
            groundZero: "action",
          },
          {
            id: "stop-check",
            icon: "stop",
            title: "Stop check",
            summary: "Stops when the stop word is picked or the text is full.",
            copies: 1,
            facts: { shape: "stop word, or full length", weightCount: 0, headline: { value: spec.stopWord.id, unit: "is the stop word's ID", isComputed: spec.stopWord.isComputed, isId: true }, input: "pick and length", output: "go on, or stop", inputDetail: "the picked word and the length", sources: stopSources, notes: spec.stopWord.notes, reasons: spec.reasons["stop-check"] },
            explanation: `Compare the picked word with the stop word, and the length with ${count(spec.context)} words. Stop if either matches.`,
            why: "The model does not decide it is finished. It picks the stop word like any other word.",
            story: {
              problem: "Left alone, the loop would write until the text is full. Without a stop check an answer could not end where it should, and would run on to the length limit.",
              demo: "generate",
              when: "Once per round, after each word is added. Apps also let you set a length limit or stop words of your own.",
              feeds: "If nothing says stop, the next round starts with the longer text; otherwise the answer is done.",
              nextId: "write-round",
            },
            formula: { lines: ["stop if word = stop word", `or length = ${count(spec.context)}`] },
            groundZero: "action",
          },
        ],
      },
      {
        id: "kv-cache",
        icon: "cache",
        title: "KV cache",
        summary: "Saves work done for earlier words, so each new word runs faster.",
        copies: 1,
        facts: { shape: `2 × ${count(spec.kvWidth)} numbers per word, per layer`, weightCount: 0, headline: { value: 2 * spec.kvWidth, unit: "saved per word, per layer", isComputed: true }, input: "new keys and values", output: "saved for reuse", inputDetail: "each new word's keys and values", outputDetail: "earlier keys and values, ready to reuse", sources: spec.sources, notes: [{ label: "A full text", value: `${count(2 * spec.kvWidth * layerCount * spec.context)} numbers for ${count(spec.context)} words in all ${layerCount} layers, worked out`, source: spec.sources[0] }], reasons: spec.reasons["kv-cache"] },
        explanation: "Save one word's key and value from one layer, so the next round reads them back instead of working them out again. Only the new word is run through the layers.",
        why: "It changes nothing about the answer, only the speed. These are saved results, not stored numbers learned in training.",
        story: {
          problem: "Each round the model would read the whole text again, though the earlier words' keys and values have not changed. Without saving them, every new word would cost more work than the one before.",
          demo: "kv-cache",
          when: "Whenever a model writes more than one word. It trades memory for speed: the saved numbers grow with every word of the text.",
          feeds: "Each layer's attention reads the saved keys and values back, beside the new word's own.",
          nextId: "layers",
        },
        formula: { lines: ["cache[layer].push(key, value)"] },
        groundZero: "action",
      },
    ],
  };
}
