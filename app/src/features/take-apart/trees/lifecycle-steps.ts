function tokenizerStep(facts: BuildFacts): ModelPart {
  return {
    id: "tokenizer",
    icon: "text",
    title: "Tokenizer",
    summary: "Builds the word list the model will use, by counting common pairs of letters.",
    copies: 1,
    facts: stepFacts(facts.tokenizer, "clean text", "a word list", { inputDetail: "clean training text", outputDetail: "a word list: piece ↔ ID" }),
    lesson: "Lessons 09, 18",
    reverseLesson: "RL-01",
    explanation: "Build the list of words the model will use. BPE starts from single bytes, then keeps joining the most common pair of neighbouring pieces into a new piece, until the list is full.",
    why: "The list is made by counting, not by meaning. Common words become one piece; rare words stay in parts.",
    story: {
      problem: "A model works on a fixed list of pieces. Whole words would leave out every rare or new word, and single letters would make texts far too long; the tokenizer finds the middle ground.",
      demo: "gpt-2-tokenizer",
      when: "After the data is ready and before the model is written, because the list's size sets the word table's size.",
      feeds: "The word list fixes how many rows the word table has and turns every training text into IDs.",
      nextId: "merge-round",
    },
    formula: { lines: ["repeat: count pairs, merge the top pair", "until the list is full"] },
    children: [
      {
        id: "merge-round",
        icon: "repeat",
        title: "One merge round",
        summary: "Joins the most common pair of pieces into one new piece.",
        copies: 1,
        facts: stepFacts(facts["merge-round"], "text in pieces", "1 new piece, 1 rule", { inputDetail: "the text, split into pieces", outputDetail: "one new piece and one rule" }),
        lesson: "Lesson 18",
        reverseLesson: "RL-01",
        explanation: "Count every pair of neighbouring pieces in the text, join the most common pair into one new piece, and write that down as a merge rule.",
        why: "The rules are kept in order. Using the model later replays them on new text.",
        story: {
          problem: "Starting from single bytes, every word is many pieces long. Each round joins the most common pair into one piece, so common words end up as one piece.",
          demo: "bpe-learn",
          when: "Over and over while building the tokenizer, until the list reaches the size you chose.",
          feeds: "Each round adds one merge rule and one new piece to the list.",
          nextId: "count-pair",
        },
        formula: { lines: ["top = most common pair", "rules.push(top)"] },
        children: [
          {
            id: "count-pair",
            icon: "hash",
            title: "Count one pair",
            summary: "Adds 1 to the count for one pair of side-by-side pieces.",
            copies: 1,
            facts: stepFacts(facts["count-pair"], "two pieces", "their count, plus 1", { inputDetail: "two neighbouring pieces" }),
            lesson: "Lesson 18",
            reverseLesson: "RL-01",
            explanation: "Ground zero. Add 1 to the count for one pair of neighbouring pieces, such as \"d\" then \"o\".",
            why: "The tokenizer is built from counts like this, nothing more.",
            story: {
              problem: "To know which pair to join, you must know which pair is most common. Counting is the only way the tokenizer learns anything.",
              demo: "bpe-learn",
              when: "At the start of every merge round, once for every side-by-side pair in the training text.",
              feeds: "The counts pick the top pair, which becomes the next merge rule.",
              nextId: "learn-merge",
            },
            formula: { lines: ["count[a + b] = count[a + b] + 1"] },
            groundZero: "action",
          },
          {
            id: "learn-merge",
            icon: "merge",
            title: "One merge rule",
            summary: "Writes down one join rule and adds the joined piece to the list.",
            copies: 1,
            facts: stepFacts(facts["learn-merge"], "the most common pair", "one new piece"),
            lesson: "Lesson 18",
            reverseLesson: "RL-01",
            explanation: "Ground zero. Write down one rule, such as \"do\" + \"g\" → \"dog\", and add the joined piece to the list.",
            why: "\"dog\" becomes one piece because it was common, not because anything knows it is an animal.",
            story: {
              problem: "A pair joined once must be joined the same way on every text later. Writing the rule down, in order, is what makes the tokenizer give the same pieces every time.",
              demo: "bpe-learn",
              when: "At the end of every merge round, while building the tokenizer.",
              feeds: "The rules are saved in order, and the new piece gets the next free ID.",
              nextId: "assign-id",
            },
            formula: { lines: ["rule: \"do\" + \"g\" → \"dog\""] },
            groundZero: "action",
          },
        ],
      },
      {
        id: "assign-id",
        icon: "hash",
        title: "Give one piece an ID",
        summary: "Writes one piece into the list, and its place number becomes its ID.",
        copies: 1,
        facts: stepFacts(facts["assign-id"], "one piece", "its number"),
        lesson: "Lesson 09",
        reverseLesson: "RL-01",
        explanation: "Ground zero. Write one piece and its place number into the list. That number is its ID from now on.",
        why: "The ID is only a place in a list. Nearby IDs mean nothing.",
        story: {
          problem: "The model can only take numbers in. Each piece needs one fixed number, its ID, so the same piece always picks the same row of the word table.",
          demo: "gpt-2-tokenizer",
          when: "While building the tokenizer, once for each piece in the list; after that the IDs never change.",
          feeds: "Every training text is turned into IDs, and each ID picks its row in the word table.",
          nextId: "architecture",
        },
        formula: { lines: ["list[id] = piece"] },
        groundZero: "action",
      },
    ],
  };
}

function architectureStep(model: ModelPart): ModelPart {
  return {
    id: "architecture",
    icon: "network",
    title: "Architecture",
    summary: "Writes the model as code, with every stored number starting out random.",
    copies: 1,
    facts: { shape: model.facts.shape, weightCount: model.facts.weightCount, headline: model.facts.headline, input: "sizes and parts", output: "a random model", outputDetail: "code with random numbers", sources: model.facts.sources, reasons: model.facts.reasons },
    lesson: "Lessons 13, 14, 20",
    reverseLesson: "RL-05",
    explanation: "Write the model as code: the word table, the layers of attention and feed-forward with their norms and add-backs, and the output head. Every stored number starts random.",
    why: "Before training, this exact code with random numbers writes nonsense. The shape alone knows nothing.",
    story: {
      problem: "Training needs something to adjust. Without the model's code and its tables of numbers, there would be nothing to train and nothing to run.",
      demo: "architecture",
      when: "After the word list is fixed and before training: you choose the sizes and write the code once.",
      feeds: "The model, with random numbers, goes into pre-training, which sets every number.",
      nextId: "pre-training",
    },
    formula: { lines: ["numbers = random()", "model = layers(numbers)"] },
    children: [model],
  };
}

export function lifecycleRoot(model: ModelPart, facts: BuildFacts): ModelPart {
  return {
    id: "build",
    icon: "pen",
    title: "Build a model",
    summary: "How a model is made, from raw text to a model you can use, in 6 stages.",
    copies: 1,
    facts: { shape: "6 stages", weightCount: model.facts.weightCount, headline: model.facts.headline, input: "online text", output: "a model ready to use", inputDetail: "publicly available online text", sources: model.facts.sources },
    lesson: "Lessons 14, 30",
    reverseLesson: "RL-05",
    explanation: "How a model is made: collect text, build the word list, write the model code, train it to guess the next word, teach it to answer, then test and shrink it.",
    why: "Only the architecture stage holds stored numbers. Every other stage shapes what those numbers end up being.",
    formula: { lines: ["data → word list → code → pre-train → post-train → test"] },
    children: [
      dataStep(facts),
      tokenizerStep(facts),
      architectureStep(model),
      preTrainingStep(facts),
      postTrainingStep(facts),
      evaluationStep(facts),
    ],
  };
}
